using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Threading.Tasks;

namespace StellarisNameListGenerator.ArchitectureTests.Infrastructure
{
    /// <summary>
    /// Loads and caches all handwritten production and test source files for the architecture and convention checks.
    /// </summary>
    public sealed class SourceFileLoader
    {
        static readonly string[] DefaultExcludedDirectories = ["bin", "obj", ".git", ".cache"];

        readonly string repositoryRoot;
        IReadOnlyList<SourceFile> cachedFiles;

        public SourceFileLoader(string repositoryRoot)
        {
            this.repositoryRoot = repositoryRoot;
        }

        public IReadOnlyList<SourceFile> Load()
        {
            if (cachedFiles is not null)
            {
                return cachedFiles;
            }

            string productionRoot = Path.Combine(repositoryRoot, "StellarisNameListGenerator");
            string unitTestRoot = Path.Combine(repositoryRoot, "StellarisNameListGenerator.UnitTests");
            string architectureTestRoot = Path.Combine(repositoryRoot, "StellarisNameListGenerator.ArchitectureTests");

            List<SourceFile> files = [];
            files.AddRange(LoadFiles(productionRoot, "StellarisNameListGenerator"));
            files.AddRange(LoadFiles(unitTestRoot, "StellarisNameListGenerator.UnitTests"));
            files.AddRange(LoadFiles(architectureTestRoot, "StellarisNameListGenerator.ArchitectureTests"));

            if (files.Count == 0)
            {
                throw new InvalidOperationException(
                    "No eligible handwritten source files were found. Source-file convention tests " +
                    "require explicit production and test sources and must not pass vacuously.");
            }

            cachedFiles = files.AsReadOnly();
            return cachedFiles;
        }

        public IReadOnlyList<SourceFile> LoadProduction()
            => Load().Where(f => f.ProjectName == "StellarisNameListGenerator").ToList();

        public IReadOnlyList<SourceFile> LoadTests()
            => Load().Where(f => f.ProjectName != "StellarisNameListGenerator").ToList();

        List<SourceFile> LoadFiles(string projectRoot, string projectName)
        {
            if (!Directory.Exists(projectRoot))
            {
                throw new InvalidOperationException(
                    $"The required project directory '{projectRoot}' does not exist. " +
                    "Architecture tests fail when required inputs are unavailable.");
            }

            List<SourceFile> files = [];

            foreach (string path in Directory.EnumerateFiles(projectRoot, "*.cs", SearchOption.AllDirectories))
            {
                string unifiedPath = path.Replace('\\', '/');
                string relativeRoot = projectRoot.Replace('\\', '/') + "/";

                if (unifiedPath.Contains(relativeRoot + "bin/") || unifiedPath.Contains(relativeRoot + "obj/"))
                {
                    continue;
                }

                if (DefaultExcludedDirectories.Any(d => unifiedPath.Contains($"/{d}/")))
                {
                    continue;
                }

                string content = File.ReadAllText(path);

                if (content.Contains("<auto-generated") || Path.GetFileName(path).StartsWith("TemporaryGeneratedFile_"))
                {
                    continue;
                }

                files.Add(new SourceFile(
                    projectName,
                    unifiedPath,
                    Path.GetFileNameWithoutExtension(path),
                    content));
            }

            return files;
        }
    }

    public sealed record SourceFile(string ProjectName, string FilePath, string FileNameStem, string Content);
}
