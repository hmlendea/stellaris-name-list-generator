        public void GivenANewModel_WhenReadingACollectionPropertyTwice_ThenTheSameInstanceIsReturned(string typeName, string propertyName)
        {
            object instance = Create(typeName);

            Assert.That(Get(instance, propertyName), Is.SameAs(Get(instance, propertyName)));
        }

        private static object Create(string typeName)
            => typeName switch
            {
                "ArmyNames" => new ArmyNames(),
                "BiosphereNames" => new BiosphereNames(),
                "CharacterNames" => new CharacterNames(),
                "CompanyNames" => new CompanyNames(),
                "GreatPeople" => new GreatPeople(),
                "MilitaryStationNames" => new MilitaryStationNames(),
                "NameList" => new NameList(),
                "PlaceNames" => new PlaceNames(),
                "PlanetNames" => new PlanetNames(),
                "ShipNames" => new ShipNames(),
                "StationNames" => new StationNames(),
                "WarfareNames" => new WarfareNames(),
                "WeaponNames" => new WeaponNames(),
                _ => throw new System.ArgumentOutOfRangeException(nameof(typeName), typeName, "Unknown model"),
            };

        private static IList Get(object instance, string propertyName)
        {
            PropertyInfo? property = instance.GetType().GetProperty(propertyName);

            Assert.That(property, Is.Not.Null, $"{propertyName} is missing");

            IList? values = (IList?)property!.GetValue(instance);

            Assert.That(values, Is.Not.Null, $"{propertyName} returned null");

            return values!;
        }
